/* ================= the Trench Cafe emblem: a pixel mug whose steam is three green candles going up ================= */
function emblemSVG(o = {}) {
  const fg = o.fg || '#ffffff', bg = o.bg || null, acc = o.acc || '#8fd3a6', ink = o.ink || (fg === '#000000' ? '#ffffff' : '#0a0a0b'), ring = o.ring !== false, size = o.size || 200;
  const ticks = []; for (let i = 0; i < 36; i++) { const a = i / 36 * Math.PI * 2; const r1 = 78, r2 = i % 9 === 0 ? 70 : 74; ticks.push(`<line x1="${(100 + Math.sin(a) * r1).toFixed(1)}" y1="${(100 - Math.cos(a) * r1).toFixed(1)}" x2="${(100 + Math.sin(a) * r2).toFixed(1)}" y2="${(100 - Math.cos(a) * r2).toFixed(1)}"/>`); }
  const px = (c, r, col) => `<rect x="${c * 10}" y="${r * 10}" width="10" height="10" fill="${col}"/>`;
  const cells = [];
  for (let r = 9; r <= 17; r++) for (let c = 4; c <= 12; c++) { if (r === 17 && (c === 4 || c === 12)) continue; cells.push(px(c, r, fg)); }   // the mug
  for (let c = 5; c <= 11; c++) cells.push(px(c, 9, ink));                                                                                   // the coffee
  for (const [c, r] of [[13, 11], [14, 11], [14, 12], [14, 13], [14, 14], [13, 15], [14, 15]]) cells.push(px(c, r, fg));                       // the handle
  for (const [c, bt, bb, wt, wb] of [[6, 6, 7, 5, 8], [8, 4, 7, 3, 8], [10, 2, 5, 1, 7]]) {                                                   // three green candles as steam, each higher than the last
    cells.push(`<rect x="${c * 10 + 4}" y="${wt * 10}" width="2" height="${(wb - wt + 1) * 10}" fill="${acc}"/>`);
    for (let r = bt; r <= bb; r++) cells.push(px(c, r, acc));
  }
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 200 200" width="${size}" height="${size}" role="img" aria-label="Trench Cafe">
  ${bg ? `<circle cx="100" cy="100" r="98" fill="${bg}"/>` : ''}
  <circle cx="100" cy="100" r="90" fill="none" stroke="${fg}" stroke-width="7"/>
  ${ring ? `<defs><path id="ccring" d="M100,100 m-70,0 a70,70 0 1,1 140,0 a70,70 0 1,1 -140,0"/></defs><text font-family="Unbounded,'Arial Black',sans-serif" font-weight="900" font-size="9.4" letter-spacing="1.6" fill="${fg}"><textPath href="#ccring" startOffset="0">TRENCH CAFE · EVERY DESK IS A LIVE COIN · SOLANA ·</textPath></text>` : `<g stroke="${fg}" stroke-width="2.4" stroke-linecap="round" opacity=".9">${ticks.join('')}</g>`}
  <g shape-rendering="crispEdges" transform="translate(100 ${ring ? 104 : 102}) scale(${ring ? .62 : .78}) translate(-100 -100)">${cells.join('')}</g>
</svg>`;
}
